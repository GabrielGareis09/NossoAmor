const coverScreen = document.getElementById("coverScreen");
const bookScreen = document.getElementById("bookScreen");
const bookCover = document.getElementById("bookCover");
const book = document.getElementById("book");
const prevBtn = document.getElementById("prevBtn");
const nextBtn = document.getElementById("nextBtn");
const pageIndicator = document.getElementById("pageIndicator");
const endOptions = document.getElementById("endOptions");
const rereadBtn = document.getElementById("rereadBtn");
const backLoginBtn = document.getElementById("backLoginBtn");
const heartsContainer = document.querySelector(".hearts");

let currentPage = 0;
const totalPages = pagesData.length;

function createPages() {
    book.innerHTML = "";

    pagesData.forEach((data, index) => {
        const page = document.createElement("div");
        page.classList.add("page");
        if (index === 0) page.classList.add("active");
        else page.classList.add("behind");

        page.innerHTML = `
            <div class="page-header">${data.header}</div>
            <h2 class="page-title">${data.title}</h2>
            <div class="page-content">${data.content}</div>
            <span class="page-number">${index + 1}</span>
        `;

        book.appendChild(page);
    });
}

function updatePages() {
    const pages = document.querySelectorAll(".page");

    pages.forEach((page, index) => {
        page.classList.remove("active", "flipped", "behind");

        if (index < currentPage) {
            page.classList.add("flipped");
        } else if (index === currentPage) {
            page.classList.add("active");
        } else {
            page.classList.add("behind");
        }
    });

    pageIndicator.textContent = `${currentPage + 1} / ${totalPages}`;
    prevBtn.disabled = currentPage === 0;
    nextBtn.disabled = currentPage === totalPages - 1;

    if (currentPage === totalPages - 1) {
        endOptions.classList.remove("hidden");
    } else {
        endOptions.classList.add("hidden");
    }
}

function nextPage() {
    if (currentPage < totalPages - 1) {
        currentPage++;
        updatePages();
    }
}

function prevPage() {
    if (currentPage > 0) {
        currentPage--;
        updatePages();
    }
}

function openBook() {
    coverScreen.classList.add("hidden");
    bookScreen.classList.remove("hidden");
    createPages();
    updatePages();
}

bookCover.addEventListener("click", openBook);

prevBtn.addEventListener("click", prevPage);
nextBtn.addEventListener("click", nextPage);

document.addEventListener("keydown", (e) => {
    if (bookScreen.classList.contains("hidden")) return;

    if (e.key === "ArrowRight" || e.key === " ") {
        e.preventDefault();
        nextPage();
    } else if (e.key === "ArrowLeft") {
        e.preventDefault();
        prevPage();
    }
});

rereadBtn.addEventListener("click", () => {
    currentPage = 0;
    updatePages();
    endOptions.classList.add("hidden");
});

backLoginBtn.addEventListener("click", () => {
    window.location.href = "index.html";
});
const galleryBtn = document.getElementById("galleryBtn");

galleryBtn.addEventListener("click", () => {
    window.location.href = "galeria.html";
});


function createHeart() {
    const heart = document.createElement("div");
    heart.classList.add("floating-heart");
    heart.innerHTML = "♥";
    heart.style.left = Math.random() * 100 + "%";
    heart.style.fontSize = (10 + Math.random() * 14) + "px";
    heart.style.animationDuration = (7 + Math.random() * 5) + "s";
    heart.style.animationDelay = Math.random() * 2 + "s";
    heartsContainer.appendChild(heart);

    setTimeout(() => {
        heart.remove();
    }, 14000);
}

setInterval(createHeart, 1100);